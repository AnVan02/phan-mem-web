    <script>
    (function () {
        var prevBtn = document.getElementById('servicesPrevBtn');
        var nextBtn = document.getElementById('servicesNextBtn');
        var tabLinks = document.querySelectorAll('.services-tab-item');
        var tabPanes = document.querySelectorAll('.services-tab-pane');

        function getActiveGrid() {
            return document.querySelector('.services-tab-pane.active .services-grid');
        }

        function getScrollStep(grid) {
            if (!grid) return 320;
            var card = grid.querySelector('.service-card');
            if (!card) return 320;
            var gap = parseFloat(getComputedStyle(grid).gap) || 24;
            return card.offsetWidth + gap;
        }

        if (nextBtn) {
            nextBtn.addEventListener('click', function () {
                var grid = getActiveGrid();
                if (grid) grid.scrollBy({ left: getScrollStep(grid), behavior: 'smooth' });
            });
        }

        if (prevBtn) {
            prevBtn.addEventListener('click', function () {
                var grid = getActiveGrid();
                if (grid) grid.scrollBy({ left: -getScrollStep(grid), behavior: 'smooth' });
            });
        }

        tabLinks.forEach(function (link) {
            link.addEventListener('click', function (e) {
                e.preventDefault();
                var targetId = this.getAttribute('data-tab');

                tabLinks.forEach(function (l) { l.classList.remove('active'); });
                this.classList.add('active');

                tabPanes.forEach(function (pane) {
                    if (pane.id === targetId) {
                        pane.classList.add('active');
                    } else {
                        pane.classList.remove('active');
                    }
                });
            });
        });
    })();
    </script>